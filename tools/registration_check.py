"""Compile current engine/parser sources together without the Eclipse UI/Tycho reactor.

Xtend is regenerated by its compiler into output/function-registration, never edited.
This focused check complements, and does not replace, the normal release build.
"""
import argparse
from pathlib import Path
import subprocess
import shutil
import tempfile
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
PARENT = ROOT / "rule-engine-expression-parser/com.act21.rule.engine.dsl.expression.parent"
DSL = PARENT / "com.act21.rule.engine.dsl.expression"
RUNTIME = PARENT / "com.act21.rule.engine.dsl.expression.Runtime"
ENGINE = ROOT / "rule-engine"
OUT = ROOT / "output/function-registration"


def main():
    global PARENT, DSL, RUNTIME, ENGINE, OUT
    sys.stdout.reconfigure(errors="replace")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--test", default="RegisteredFunctionsTest")
    parser.add_argument("--compile-only", action="store_true")
    parser.add_argument("--workspace", type=Path, default=ROOT,
                        help="Containing folder with engine and parser repositories")
    parser.add_argument("--output", type=Path, default=OUT)
    parser.add_argument("--java", default="C:/Program Files/jdk-17.0.9/bin/java.exe")
    parser.add_argument("--maven-home", default="C:/Program Files/apache-maven-3.9.6-bin/apache-maven-3.9.6")
    args = parser.parse_args()
    PARENT = args.workspace.resolve() / "rule-engine-expression-parser/com.act21.rule.engine.dsl.expression.parent"
    DSL = PARENT / "com.act21.rule.engine.dsl.expression"
    RUNTIME = PARENT / "com.act21.rule.engine.dsl.expression.Runtime"
    ENGINE = args.workspace.resolve() / "rule-engine"
    OUT = args.output.resolve()
    OUT.mkdir(parents=True, exist_ok=True)
    if not (DSL / "src-gen/com/act21/rule/engine/dsl/Expression.xtextbin").exists():
        raise SystemExit("Generate the Xtext language sources through Eclipse/MWE2 first.")
    ns = {"m": "https://maven.apache.org/POM/4.0.0"}
    source = ET.parse(ENGINE / "pom.xml").getroot()
    dependencies = source.find("m:dependencies", ns)
    for node in list(dependencies):
        artifact = node.find("m:artifactId", ns)
        if artifact is not None and artifact.text.strip() == "com.act21.rule.engine.dsl.expression.runtime":
            dependencies.remove(node)
    # Remove namespaces from the copied engine dependencies for the standalone POM.
    for node in dependencies.iter():
        node.tag = node.tag.split("}")[-1]
        if node.text:
            node.text = node.text.strip()
    for group, artifact, version in [
        ("org.eclipse.xtext", "org.eclipse.xtext", "2.28.0"),
        ("org.eclipse.xtext", "org.eclipse.xtext.xbase", "2.28.0"),
        ("org.eclipse.xtend", "org.eclipse.xtend.lib", "2.28.0"),
        ("org.apache.commons", "commons-lang3", "3.12.0"),
        ("org.apache.commons", "commons-text", "1.9"),
        ("org.json", "json", "20210307"),
    ]:
        dependency = ET.SubElement(dependencies, "dependency")
        for name, value in [("groupId", group), ("artifactId", artifact), ("version", version)]:
            ET.SubElement(dependency, name).text = value
    # Xtend requires sources below its project directory; compile exact staged copies.
    stage = Path(tempfile.mkdtemp(prefix="sources-", dir=OUT))
    sources = []
    for name, original in [("dsl", DSL / "src"), ("model", DSL / "src-gen"),
                           ("runtime", RUNTIME / "src"), ("engine", ENGINE / "src/main/java")]:
        destination = stage / name
        shutil.copytree(original, destination)
        sources.append(destination)
    resources = sources[:2] + [ENGINE / "src/main/resources"]
    source_xml = "".join(f"<source>{p.as_posix()}</source>" for p in sources)
    resource_xml = "".join(f"<resource><directory>{p.as_posix()}</directory>"
                           "<excludes><exclude>**/*.java</exclude><exclude>**/*.xtend</exclude></excludes>"
                           "</resource>" for p in resources)
    pom = f"""<project xmlns="http://maven.apache.org/POM/4.0.0">
<modelVersion>4.0.0</modelVersion><groupId>local.verification</groupId>
<artifactId>function-registration-check</artifactId><version>1.0-SNAPSHOT</version>
<properties><maven.compiler.source>17</maven.compiler.source><maven.compiler.target>17</maven.compiler.target>
<project.build.sourceEncoding>UTF-8</project.build.sourceEncoding></properties>
<repositories><repository><id>ImpaktAppsRepository</id>
<url>https://artifactory.act21.io/artifactory/act21_internal_repo</url></repository></repositories>
{ET.tostring(dependencies, encoding='unicode')}
<build><testSourceDirectory>{(ENGINE / 'src/test/java').as_posix()}</testSourceDirectory>
<resources>{resource_xml}</resources><testResources><testResource>
<directory>{(ENGINE / 'src/test/resources').as_posix()}</directory></testResource></testResources>
<plugins><plugin><groupId>org.codehaus.mojo</groupId><artifactId>build-helper-maven-plugin</artifactId>
<version>3.4.0</version><executions><execution><phase>generate-sources</phase><goals><goal>add-source</goal></goals>
<configuration><sources>{source_xml}</sources></configuration></execution></executions></plugin>
<plugin><groupId>org.eclipse.xtend</groupId><artifactId>xtend-maven-plugin</artifactId><version>2.28.0</version>
<executions><execution><goals><goal>compile</goal></goals></execution></executions>
<configuration><javaSourceVersion>11</javaSourceVersion>
<outputDirectory>{(OUT / 'xtend-gen').as_posix()}</outputDirectory></configuration></plugin>
<plugin><groupId>org.apache.maven.plugins</groupId><artifactId>maven-compiler-plugin</artifactId><version>3.10.1</version>
<configuration><proc>none</proc></configuration></plugin>
<plugin><groupId>org.apache.maven.plugins</groupId><artifactId>maven-surefire-plugin</artifactId><version>3.2.5</version>
<configuration><workingDirectory>{ENGINE.as_posix()}</workingDirectory></configuration></plugin>
</plugins></build></project>"""
    (OUT / "pom.xml").write_text(pom, encoding="utf-8")
    maven = Path(args.maven_home)
    launcher = next((maven / "boot").glob("plexus-classworlds-*.jar"))
    command = [args.java, f"-Dclassworlds.conf={maven / 'bin/m2.conf'}", f"-Dmaven.home={maven}",
               f"-Dmaven.multiModuleProjectDirectory={OUT}", "-classpath", str(launcher),
               "org.codehaus.plexus.classworlds.launcher.Launcher", "-B", "-f", str(OUT / "pom.xml")]
    if args.offline:
        command.append("-o")
    command += ["compile"] if args.compile_only else [f"-Dtest={args.test}", "test"]
    (ENGINE / "src-gen").mkdir(exist_ok=True)
    with (OUT / "build.log").open("w", encoding="utf-8") as log:
        result = subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
    print("Build log:", OUT / "build.log")
    print("\n".join((OUT / "build.log").read_text(encoding="utf-8", errors="replace").splitlines()[-45:]))
    raise SystemExit(result.returncode)


if __name__ == "__main__":
    main()
